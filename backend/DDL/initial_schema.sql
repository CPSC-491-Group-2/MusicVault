-- ============================================================
-- 19. IMPORTANT DESIGN NOTES
-- ============================================================

/*
1. users.email is nullable.
   Spotify-only registration must not depend on email.

2. spotify_accounts is optional.
   A MusicVault user can exist without linking Spotify.

3. songs.spotify_track_id is nullable.
   Songs may originate from non-Spotify chart or metadata sources.

4. popularity is provider-neutral.
   Spotify does not reliably provide track popularity for current
   Development Mode applications.

5. audio_features is provider-neutral.
   Spotify Audio Features is not assumed to be available.

6. charts are source-neutral.
   MusicVault's Top 100 feature must not depend on Spotify-owned
   editorial/chart playlists.

7. recommendations are generated and owned by MusicVault.
   They do not represent Spotify's removed Recommendations API.

8. OAuth credentials must never be committed to Git.
   Production token storage may later be encrypted or moved into
   a dedicated secure credential mechanism.

9. user_top_songs is a snapshot, not a history.
   Saving a user's top songs for a time range replaces the
   previous list for that range. The unique (user_id, time_range,
   rank) constraint also serves the "list in rank order" lookup.

10. Genres belong to artists, not songs.
    Spotify only exposes genres on artist objects, so a song's
    genres are the union of its credited artists' genres.

11. songs.isrc is not unique.
    The same recording can be released under several Spotify track
    IDs. It is kept for looking songs up in other music databases.

12. songs.preview_url is perishable.
    Deezer preview links are signed and expire, so a stored value
    can stop playing at any time. Treat it as a short-lived cache
    to refresh on use, never as stable catalog data, and never as
    a permalink shown to users.

13. artist_edges is directed, not symmetric.
    A row means the provider listed dst as similar to src, which
    does not imply the reverse. Store each direction the provider
    actually reported and query both columns when similarity is
    wanted in either direction; that is why both src and dst have
    their own index.

14. crawl_jobs.target is not a foreign key.
    It holds a provider's own identifier, so work can be queued
    for an artist or song MusicVault has not stored yet. The
    unique (kind, target) pair is what keeps the queue from
    holding the same job twice.

15. swipe_events is an append-only log.
    user_preferences holds the user's current sentiment for a
    song; swipe_events records each individual decision, so the
    ranking code can be evaluated against what users actually did
    at a given algorithm_version.
*/