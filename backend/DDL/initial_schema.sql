-- ============================================================
-- MUSICVAULT INITIAL DATABASE SCHEMA
-- PostgreSQL / Supabase
-- ============================================================


-- ============================================================
-- 1. EXTENSIONS
-- ============================================================

CREATE EXTENSION IF NOT EXISTS "pgcrypto";


-- ============================================================
-- 2. USERS
-- Core MusicVault user accounts.
-- Email is nullable because Spotify no longer guarantees email.
-- ============================================================

CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    email VARCHAR(320),
    password_hash TEXT NULL,
    auth_version INTEGER NOT NULL DEFAULT 1,
    display_name VARCHAR(255),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================
-- 3. LINKED SPOTIFY ACCOUNTS
-- Stores the user's linked Spotify identity and OAuth metadata.
-- spotify_account_id should be treated as the stable external
-- account-linking identifier.
-- ============================================================

CREATE TABLE spotify_accounts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL UNIQUE
        REFERENCES users(id)
        ON DELETE CASCADE,

    spotify_account_id VARCHAR(255) NOT NULL UNIQUE,

    spotify_user_id VARCHAR(255),
    display_name VARCHAR(255),
    email VARCHAR(320),

    access_token TEXT,
    refresh_token TEXT,
    token_expires_at TIMESTAMPTZ,
    scope TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================
-- 4. SONGS
-- Canonical MusicVault song records.
-- Spotify metadata is optional; Spotify is not assumed to be
-- the authoritative source for all song data.
-- ============================================================

CREATE TABLE songs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    title VARCHAR(500) NOT NULL,
    artist_name VARCHAR(500) NOT NULL,
    album_name VARCHAR(500),

    spotify_track_id VARCHAR(255) UNIQUE,
    isrc VARCHAR(32),

    deezer_track_id VARCHAR(255),
    preview_url TEXT,

    duration_ms INTEGER,
    explicit BOOLEAN,

    popularity INTEGER,
    popularity_source VARCHAR(100),

    audio_features JSONB,
    audio_features_source VARCHAR(100),

    spotify_url TEXT,
    album_image_url TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_song_duration_nonnegative
        CHECK (duration_ms IS NULL OR duration_ms >= 0),

    CONSTRAINT chk_song_popularity_range
        CHECK (
            popularity IS NULL
            OR popularity BETWEEN 0 AND 100
        )
);


-- ============================================================
-- 5. USER SONG PREFERENCES
-- Stores user sentiment / interaction with songs.
-- Allows MusicVault to build recommendation signals internally.
-- ============================================================

CREATE TABLE user_preferences (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL
        REFERENCES users(id)
        ON DELETE CASCADE,

    song_id UUID NOT NULL
        REFERENCES songs(id)
        ON DELETE CASCADE,

    preference_type VARCHAR(50) NOT NULL,
    rating SMALLINT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_user_preferences_user_song
        UNIQUE (user_id, song_id),

    CONSTRAINT chk_user_preferences_rating
        CHECK (
            rating IS NULL
            OR rating BETWEEN 1 AND 5
        ),

    CONSTRAINT chk_user_preferences_type
        CHECK (
            preference_type IN (
                'liked',
                'disliked',
                'saved',
                'skipped',
                'neutral'
            )
        )
);


-- ============================================================
-- 6. RECOMMENDATIONS
-- Stores recommendations generated by MusicVault.
-- Does NOT assume Spotify's removed Recommendations endpoint.
-- ============================================================

CREATE TABLE recommendations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL
        REFERENCES users(id)
        ON DELETE CASCADE,

    song_id UUID NOT NULL
        REFERENCES songs(id)
        ON DELETE CASCADE,

    score DOUBLE PRECISION,
    reason TEXT,
    algorithm_version VARCHAR(100),

    generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_recommendations_user_song
        UNIQUE (user_id, song_id),

    CONSTRAINT chk_recommendation_score
        CHECK (
            score IS NULL
            OR score >= 0
        )
);


-- ============================================================
-- 7. CHARTS
-- Represents external or internally generated charts.
-- The chart source is provider-neutral and should not assume
-- Spotify is the source.
-- ============================================================

CREATE TABLE charts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    name VARCHAR(255) NOT NULL,
    source VARCHAR(100) NOT NULL,
    chart_date DATE NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_charts_name_source_date
        UNIQUE (name, source, chart_date)
);


-- ============================================================
-- 8. CHART ENTRIES
-- Connects songs to charts and stores their ranking position.
-- ============================================================

CREATE TABLE chart_entries (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    chart_id UUID NOT NULL
        REFERENCES charts(id)
        ON DELETE CASCADE,

    song_id UUID NOT NULL
        REFERENCES songs(id)
        ON DELETE CASCADE,

    position INTEGER NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_chart_entries_chart_position
        UNIQUE (chart_id, position),

    CONSTRAINT uq_chart_entries_chart_song
        UNIQUE (chart_id, song_id),

    CONSTRAINT chk_chart_position_positive
        CHECK (position > 0)
);


-- ============================================================
-- 9. USER TOP SONGS
-- A user's ranked top songs from Spotify, one list per time
-- range. Each refresh replaces that user's list for the range.
-- Song details live in songs, shared across users.
-- ============================================================

CREATE TABLE user_top_songs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL
        REFERENCES users(id)
        ON DELETE CASCADE,

    song_id UUID NOT NULL
        REFERENCES songs(id)
        ON DELETE CASCADE,

    time_range VARCHAR(20) NOT NULL,
    rank INTEGER NOT NULL,

    fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_user_top_songs_user_range_rank
        UNIQUE (user_id, time_range, rank),

    CONSTRAINT uq_user_top_songs_user_range_song
        UNIQUE (user_id, time_range, song_id),

    CONSTRAINT chk_user_top_songs_rank_positive
        CHECK (rank > 0),

    CONSTRAINT chk_user_top_songs_time_range
        CHECK (
            time_range IN (
                'short_term',
                'medium_term',
                'long_term'
            )
        )
);


-- ============================================================
-- 10. ARTISTS
-- Canonical MusicVault artist records, shared across songs.
-- genres is NULL until a genre lookup has run for the artist;
-- an empty array means the lookup ran and found none.
-- ============================================================

CREATE TABLE artists (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    name VARCHAR(500) NOT NULL,

    spotify_artist_id VARCHAR(255) UNIQUE,
    mbid VARCHAR(36),

    fans INTEGER,
    fans_source VARCHAR(100),
    last_expanded_at TIMESTAMPTZ,

    genres JSONB,
    genres_source VARCHAR(100),
    genres_fetched_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_artist_genres_array
        CHECK (genres IS NULL OR jsonb_typeof(genres) = 'array')
);


-- ============================================================
-- 11. SONG ARTISTS
-- The credited artists of each song, in credit order.
-- songs.artist_name stays as the display string.
-- ============================================================

CREATE TABLE song_artists (
    song_id UUID NOT NULL
        REFERENCES songs(id)
        ON DELETE CASCADE,

    artist_id UUID NOT NULL
        REFERENCES artists(id)
        ON DELETE CASCADE,

    position INTEGER NOT NULL,

    PRIMARY KEY (song_id, artist_id),

    CONSTRAINT uq_song_artists_song_position
        UNIQUE (song_id, position),

    CONSTRAINT chk_song_artists_position_positive
        CHECK (position > 0)
);


-- ============================================================
-- 12. ARTIST EXTERNAL IDS
-- Each provider's own ID for an artist, so crawled records can
-- be matched back to one canonical artist row.
-- ============================================================

CREATE TABLE artist_external_ids (
    artist_id UUID NOT NULL
        REFERENCES artists(id)
        ON DELETE CASCADE,

    provider VARCHAR(50) NOT NULL,
    external_id VARCHAR(255) NOT NULL,

    PRIMARY KEY (artist_id, provider),

    CONSTRAINT uq_artist_external_ids_provider_external
        UNIQUE (provider, external_id)
);


-- ============================================================
-- 13. ARTIST EDGES
-- Directed artist-to-artist similarity, one row per provider.
-- Edges are stored in the direction the provider reported them.
-- ============================================================

CREATE TABLE artist_edges (
    src_artist_id UUID NOT NULL
        REFERENCES artists(id)
        ON DELETE CASCADE,

    dst_artist_id UUID NOT NULL
        REFERENCES artists(id)
        ON DELETE CASCADE,

    provider VARCHAR(50) NOT NULL,
    weight DOUBLE PRECISION NOT NULL,

    fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (src_artist_id, dst_artist_id, provider),

    CONSTRAINT chk_artist_edges_weight_range
        CHECK (weight >= 0 AND weight <= 1),

    CONSTRAINT chk_artist_edges_no_self
        CHECK (src_artist_id <> dst_artist_id),

    CONSTRAINT chk_artist_edges_provider
        CHECK (
            provider IN (
                'deezer_related',
                'lastfm_similar',
                'mb_relation',
                'co_credit'
            )
        )
);


-- ============================================================
-- 14. ARTIST TAGS
-- Provider-supplied tags for an artist, with that provider's
-- own weight. Separate from artists.genres, which is Spotify's.
-- ============================================================

CREATE TABLE artist_tags (
    artist_id UUID NOT NULL
        REFERENCES artists(id)
        ON DELETE CASCADE,

    tag VARCHAR(100) NOT NULL,
    provider VARCHAR(50) NOT NULL,

    weight DOUBLE PRECISION,

    PRIMARY KEY (artist_id, tag, provider)
);


-- ============================================================
-- 15. CRAWL JOBS
-- The crawler's work queue. Jobs are claimed per lane, highest
-- priority first, and only once run_after has passed.
-- ============================================================

CREATE TABLE crawl_jobs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    kind VARCHAR(50) NOT NULL,
    lane VARCHAR(50) NOT NULL,
    target VARCHAR(255) NOT NULL,

    payload JSONB,

    priority INTEGER NOT NULL DEFAULT 50,
    status VARCHAR(20) NOT NULL DEFAULT 'queued',
    attempts INTEGER NOT NULL DEFAULT 0,

    run_after TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_error TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_crawl_jobs_kind_target
        UNIQUE (kind, target),

    CONSTRAINT chk_crawl_jobs_status
        CHECK (
            status IN (
                'queued',
                'running',
                'done',
                'failed'
            )
        )
);


-- ============================================================
-- 16. SWIPE EVENTS
-- A user's keep/pass/skip decisions in the swipe deck. This is
-- an append-only log, unlike user_preferences' current state.
-- ============================================================

CREATE TABLE swipe_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL
        REFERENCES users(id)
        ON DELETE CASCADE,

    song_id UUID NOT NULL
        REFERENCES songs(id)
        ON DELETE CASCADE,

    action VARCHAR(20) NOT NULL,
    deck_position INTEGER,
    algorithm_version VARCHAR(100),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_swipe_events_action
        CHECK (
            action IN (
                'keep',
                'pass',
                'skip'
            )
        )
);


-- ============================================================
-- 17. INDEXES
-- Additional indexes for common lookup and join patterns.
-- ============================================================

CREATE UNIQUE INDEX uq_users_email_ci
    ON users(lower(email));


CREATE INDEX idx_spotify_accounts_user_id
    ON spotify_accounts(user_id);


CREATE INDEX idx_spotify_accounts_spotify_account_id
    ON spotify_accounts(spotify_account_id);


CREATE INDEX idx_songs_spotify_track_id
    ON songs(spotify_track_id);


CREATE INDEX idx_songs_title
    ON songs(title);


CREATE INDEX idx_songs_artist_name
    ON songs(artist_name);


CREATE INDEX idx_user_preferences_user_id
    ON user_preferences(user_id);


CREATE INDEX idx_user_preferences_song_id
    ON user_preferences(song_id);


CREATE INDEX idx_user_preferences_type
    ON user_preferences(preference_type);


CREATE INDEX idx_recommendations_user_id
    ON recommendations(user_id);


CREATE INDEX idx_recommendations_song_id
    ON recommendations(song_id);


CREATE INDEX idx_recommendations_user_score
    ON recommendations(user_id, score DESC);


CREATE INDEX idx_charts_date
    ON charts(chart_date);


CREATE INDEX idx_charts_source
    ON charts(source);


CREATE INDEX idx_chart_entries_chart_id
    ON chart_entries(chart_id);


CREATE INDEX idx_chart_entries_song_id
    ON chart_entries(song_id);


CREATE INDEX idx_chart_entries_chart_position
    ON chart_entries(chart_id, position);


CREATE INDEX idx_user_top_songs_song_id
    ON user_top_songs(song_id);


CREATE INDEX idx_songs_isrc
    ON songs(isrc);


CREATE INDEX idx_song_artists_artist_id
    ON song_artists(artist_id);


CREATE UNIQUE INDEX IF NOT EXISTS uq_artists_mbid
    ON artists(mbid);


CREATE UNIQUE INDEX IF NOT EXISTS uq_songs_deezer_track_id
    ON songs(deezer_track_id);


CREATE INDEX IF NOT EXISTS idx_artist_edges_src_artist_id
    ON artist_edges(src_artist_id);


CREATE INDEX IF NOT EXISTS idx_artist_edges_dst_artist_id
    ON artist_edges(dst_artist_id);


CREATE INDEX IF NOT EXISTS idx_artist_external_ids_artist_id
    ON artist_external_ids(artist_id);


CREATE INDEX IF NOT EXISTS idx_crawl_jobs_claim
    ON crawl_jobs(lane, status, priority DESC, run_after);


CREATE INDEX IF NOT EXISTS idx_swipe_events_user_id
    ON swipe_events(user_id);


CREATE INDEX IF NOT EXISTS idx_swipe_events_song_id
    ON swipe_events(song_id);


