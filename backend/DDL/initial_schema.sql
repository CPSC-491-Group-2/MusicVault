-- ============================================================
-- 11. IMPORTANT DESIGN NOTES
-- ============================================================

/*
1. users.email is nullable.
   Spotify-only registration must not depend on email.

2. spotify_accounts is optional.
   A MusicVault user can exist without linking Spotify.

3. songs.spotify_track_id is nullable.
   Songs may originate from non-Spotify chart or metadata sources.

4. popularity is provider-neutral.
   Spotify does not reliably provide track popularity for current
   Development Mode applications.

5. audio_features is provider-neutral.
   Spotify Audio Features is not assumed to be available.

6. charts are source-neutral.
   MusicVault's Top 100 feature must not depend on Spotify-owned
   editorial/chart playlists.

7. recommendations are generated and owned by MusicVault.
   They do not represent Spotify's removed Recommendations API.

8. OAuth credentials must never be committed to Git.
   Production token storage may later be encrypted or moved into
   a dedicated secure credential mechanism.
*/